static void RenderEsp(ImDrawList* dl, const EspGeom& g) {
    const float* bc = (g.team && C.teamColor) ? C.teamCol : C.boxCol;
    ImU32 boxC = U32(bc);
    float cx = (g.x0 + g.x1) * 0.5f;
    float fs = C.espFontSize;

    if (C.boxFill) {
        if (C.fillGradient)
            dl->AddRectFilledMultiColor(ImVec2(g.x0, g.y0), ImVec2(g.x1, g.y1),
                U32a(C.fillCol, 0.15f), U32a(C.fillCol, 0.15f), U32a(C.fillCol, 1.f), U32a(C.fillCol, 1.f));
        else
            dl->AddRectFilled(ImVec2(g.x0, g.y0), ImVec2(g.x1, g.y1), U32(C.fillCol), C.boxStyle == 0 ? C.boxRound : 0.f);
    }
    if (C.skeleton) {
        for (int i = 0; i < g.nSeg; i++) {
            if (C.boxOutline) dl->AddLine(ImVec2(g.sa[i].x, g.sa[i].y), ImVec2(g.sb[i].x, g.sb[i].y), IM_COL32(0, 0, 0, 130), C.lineThick + 1.5f);
            dl->AddLine(ImVec2(g.sa[i].x, g.sa[i].y), ImVec2(g.sb[i].x, g.sb[i].y), U32(C.skelCol), C.lineThick);
        }
    }
    if (C.box) {
        if (C.boxOutline) BoxLines(dl, g.x0, g.y0, g.x1, g.y1, IM_COL32(0, 0, 0, 190), C.boxThick + 2.f, C.boxStyle, C.boxRound);
        BoxLines(dl, g.x0, g.y0, g.x1, g.y1, boxC, C.boxThick, C.boxStyle, C.boxRound);
    }
    if (C.headDot && g.head) {
        dl->AddCircle(ImVec2(g.headP.x, g.headP.y), g.headR, IM_COL32(0, 0, 0, 190), 24, C.lineThick + 1.5f);
        dl->AddCircle(ImVec2(g.headP.x, g.headP.y), g.headR, U32(C.headCol), 24, C.lineThick);
    }

    float barBottom = 0.f;
    if (C.health) {
        float pct = std::clamp(g.hp / std::max(g.hpMax, 1.f), 0.f, 1.f);
        float bw = C.healthW;
        ImU32 hc = HpColor(pct);
        char hb[16];
        snprintf(hb, sizeof(hb), "%.0f", g.hp);
        if (C.healthPos == 2) {
            float by0 = g.y1 + 4.f, by1 = by0 + bw;
            dl->AddRectFilled(ImVec2(g.x0 - 1, by0 - 1), ImVec2(g.x1 + 1, by1 + 1), IM_COL32(0, 0, 0, 190), 2.f);
            dl->AddRectFilled(ImVec2(g.x0, by0), ImVec2(g.x0 + (g.x1 - g.x0) * pct, by1), hc, 1.5f);
            barBottom = bw + 6.f;
            if (C.healthText) {
                ImVec2 sz = TextSz(hb, fs * 0.9f);
                EspTextAt(dl, ImVec2(g.x1 + 6, by0 + bw * 0.5f - sz.y * 0.5f), U32(C.nameCol), hb, fs * 0.9f);
            }
        } else {
            float bx0 = C.healthPos == 0 ? g.x0 - 4.f - bw : g.x1 + 4.f;
            float bx1 = bx0 + bw;
            float top = g.y1 - (g.y1 - g.y0) * pct;
            dl->AddRectFilled(ImVec2(bx0 - 1, g.y0 - 1), ImVec2(bx1 + 1, g.y1 + 1), IM_COL32(0, 0, 0, 190), 2.f);
            dl->AddRectFilled(ImVec2(bx0, top), ImVec2(bx1, g.y1), hc, 1.5f);
            if (C.healthText) {
                ImVec2 sz = TextSz(hb, fs * 0.9f);
                float tx = C.healthPos == 0 ? bx0 - 4.f - sz.x : bx1 + 4.f;
                float ty = std::max(g.y0 - 2.f, std::min(top - sz.y * 0.5f, g.y1 - sz.y));
                EspTextAt(dl, ImVec2(tx, ty), U32(C.nameCol), hb, fs * 0.9f);
            }
        }
    }
    if (C.name && g.name && g.name[0]) {
        ImVec2 sz = TextSz(g.name, fs);
        EspTextAt(dl, ImVec2(cx - sz.x * 0.5f, g.y0 - sz.y - 4.f), U32(C.nameCol), g.name, fs);
    }
    if (C.distance) {
        char b[24];
        snprintf(b, sizeof(b), "%.0fm", g.dist);
        ImVec2 sz = TextSz(b, fs * 0.92f);
        EspTextAt(dl, ImVec2(cx - sz.x * 0.5f, g.y1 + 3.f + barBottom), U32(C.distCol), b, fs * 0.92f);
    }
}

static void DrawESP(ImDrawList* dl, float w, float h, const std::vector<Ent>& ents, const Mat4& mat, const Vec3& lpos) {
    if (!C.espEnabled) return;
    for (auto& e : ents) {
        if (C.teamCheck && e.sameTeam) continue;
        float d = Dist(lpos, e.root);
        if (d > C.espMaxDist) continue;
        EspGeom g;
        if (!EntBox(e, mat, w, h, g.x0, g.y0, g.x1, g.y1)) continue;
        g.hp = e.hp; g.hpMax = e.maxHp; g.name = e.name.c_str(); g.dist = d; g.team = e.sameTeam;
        float bh = g.y1 - g.y0;
        if (C.headDot) {
            Vec2 hp;
            if (W2S(mat, e.head, w, h, hp)) { g.head = true; g.headP = hp; g.headR = std::max(2.f, bh * 0.05f); }
        }
        if (C.skeleton && e.nb > 0) {
            Vec2 sp[15];
            bool ok[15]{};
            for (int i = 0; i < e.nb; i++) ok[i] = e.bv[i] && W2S(mat, e.bp[i], w, h, sp[i]);
            int nl = e.r15 ? 14 : 5;
            for (int k = 0; k < nl; k++) {
                int a = e.r15 ? R15L[k][0] : R6L[k][0];
                int b = e.r15 ? R15L[k][1] : R6L[k][1];
                if (ok[a] && ok[b]) { g.sa[g.nSeg] = sp[a]; g.sb[g.nSeg] = sp[b]; g.nSeg++; }
            }
        }
        if (C.tracer) {
            float oy = C.tracerOrigin == 0 ? h : (C.tracerOrigin == 1 ? h * 0.5f : 0.f);
            dl->AddLine(ImVec2(w * 0.5f, oy), ImVec2((g.x0 + g.x1) * 0.5f, g.y1), U32(C.tracerCol), C.lineThick);
        }
        RenderEsp(dl, g);
    }
}

