static std::string KeyName(int vk) {
    if (vk == 0) return "None";
    switch (vk) {
        case VK_LBUTTON: return "Mouse 1";  case VK_RBUTTON: return "Mouse 2";
        case VK_MBUTTON: return "Mouse 3";  case VK_XBUTTON1: return "Mouse 4";
        case VK_XBUTTON2: return "Mouse 5";
    }
    LONG lp = (LONG)MapVirtualKeyA(vk, MAPVK_VK_TO_VSC) << 16;
    switch (vk) {
        case VK_INSERT: case VK_DELETE: case VK_HOME: case VK_END: case VK_PRIOR: case VK_NEXT:
        case VK_LEFT: case VK_RIGHT: case VK_UP: case VK_DOWN: lp |= (1 << 24);
    }
    char b[32]{};
    if (GetKeyNameTextA(lp, b, sizeof(b)) > 0) return b;
    return "Key " + std::to_string(vk);
}

