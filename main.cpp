static void DrawRadarDot(ImDrawList* dl, ImVec2 c, float R, float rx, float fz, ImU32 col) {
    float range = std::max(C.radarRange, 1.f);
    float px = rx / range * R, py = -fz / range * R;
    bool out = C.radarShape == 0 ? (std::fabs(px) > R - 4.f || std::fabs(py) > R - 4.f)
                                 : (std::sqrt(px * px + py * py) > R - 4.f);
    if (out) {
        if (!C.radarClamp) return;
        float k = C.radarShape == 0 ? (R - 4.f) / std::max(std::fabs(px), std::fabs(py))
                                    : (R - 4.f) / std::sqrt(px * px + py * py);
        px *= k; py *= k;
    }
    dl->AddCircleFilled(ImVec2(c.x + px, c.y + py), C.radarDot + 1.2f, IM_COL32(0, 0, 0, 200), 16);
    dl->AddCircleFilled(ImVec2(c.x + px, c.y + py), C.radarDot, col, 16);
}
static void DrawRadar(ImDrawList* dl, float w, float h, const std::vector<Ent>& ents, const Mat4& mat, const Vec3& lpos) {
    if (!C.radar) return;
    float R = C.radarSize * 0.5f;
    float lox = R + 6.f, hix = std::max(lox, w - R - 6.f), loy = R + 6.f, hiy = std::max(loy, h - R - 6.f);
    ImVec2 c(std::clamp(w * C.radarX / 100.f, lox, hix), std::clamp(h * C.radarY / 100.f, loy, hiy));
    DrawRadarBase(dl, c, R);
    float rx = mat.m[0], rz = mat.m[2], fx = mat.m[12], fz = mat.m[14];
    float rl = std::hypot(rx, rz), fl = std::hypot(fx, fz);
    if (rl < 1e-5f || fl < 1e-5f) return;
    rx /= rl; rz /= rl; fx /= fl; fz /= fl;
    for (auto& e : ents) {
        if (C.teamCheck && e.sameTeam) continue;
        float dx = e.root.x - lpos.x, dz = e.root.z - lpos.z;
        ImU32 col = (e.sameTeam && C.teamColor) ? U32(C.teamCol) : U32(C.radarDotCol);
        DrawRadarDot(dl, c, R, dx * rx + dz * rz, dx * fx + dz * fz, col);
    }
}

