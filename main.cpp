static void CreateLogo() {
    const int N = 128;
    if (strlen(LOGO_HEX) < (size_t)N * N * 2) return;
    auto hx = [](char c) -> int { return c >= 'a' ? c - 'a' + 10 : (c >= 'A' ? c - 'A' + 10 : c - '0'); };
    std::vector<unsigned char> px((size_t)N * N * 4);
    for (int i = 0; i < N * N; i++) {
        int v = hx(LOGO_HEX[2 * i]) * 16 + hx(LOGO_HEX[2 * i + 1]);
        px[4 * i] = px[4 * i + 1] = px[4 * i + 2] = 255;
        px[4 * i + 3] = (unsigned char)v;
    }
    D3D11_TEXTURE2D_DESC td{};
    td.Width = td.Height = N;
    td.MipLevels = 0;
    td.ArraySize = 1;
    td.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
    td.SampleDesc.Count = 1;
    td.Usage = D3D11_USAGE_DEFAULT;
    td.BindFlags = D3D11_BIND_SHADER_RESOURCE | D3D11_BIND_RENDER_TARGET;
    td.MiscFlags = D3D11_RESOURCE_MISC_GENERATE_MIPS;
    ID3D11Texture2D* tex = nullptr;
    if (FAILED(gDev->CreateTexture2D(&td, nullptr, &tex)) || !tex) return;
    gCtx->UpdateSubresource(tex, 0, nullptr, px.data(), N * 4, 0);
    D3D11_SHADER_RESOURCE_VIEW_DESC sv{};
    sv.Format = td.Format;
    sv.ViewDimension = D3D11_SRV_DIMENSION_TEXTURE2D;
    sv.Texture2D.MostDetailedMip = 0;
    sv.Texture2D.MipLevels = (UINT)-1;
    if (SUCCEEDED(gDev->CreateShaderResourceView(tex, &sv, &gLogo)) && gLogo) gCtx->GenerateMips(gLogo);
    tex->Release();
}
